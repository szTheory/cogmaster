; Owned Graphics I and II scenes (MIT). A Z80 program that loads a generated picture into
; video memory, programs the registers and idles. It records nothing and judges nothing:
; tests/fixtures/legacy.c holds the closed form picture and the runner's frame hash must
; equal its digest. One source builds five images, each selected by a -D define
; (tests/fixtures/tests.cmake):
;   V_G1          Graphics I
;   V_G2          Graphics II, R3 $FF and R4 $03: no register bit limits the tables
;   V_G2_MASKED   Graphics II, R3 $9F and R4 $00: the low bits are clear, so on a model that
;                 masks the table index with them the picture differs from V_G2
;   V_G2_LATE     mode 4 for 600 frames, then Graphics II (counted in RAM by the frame handler)
;   V_G2_SWITCH   mode 4 each frame, Graphics II from a line interrupt, mode 4 again in vertical
;                 blank: the register write lands in the middle of a line
;
; Fault prevented: a legacy background drawn from the wrong table address, the wrong colour
; nibble, the wrong third of the screen or the wrong backdrop, which an oracle written from the
; same address arithmetic as the renderer would also get wrong. Every table here is generated by
; loops from the formulas below, in the tile-index domain; the oracle never does address
; arithmetic. A game that enters a legacy mode late, or mid-frame, is the other fault: the
; renderer would take a mode 4 frame for a legacy one or the reverse.
;
; Mode names. The mode nibble is R0 bit 2, R1 bit 4, R0 bit 1, R1 bit 3 (SMS Power naming M4 M3
; M2 M1). Graphics I is nibble 0 (R0 bits 1 and 2 clear, R1 bits 3 and 4 clear), Graphics II is
; nibble 2 (R0 bit 1 set), mode 4 is nibble 8 (R0 $04) or 10 (R0 $06). The display is R1 bit 6.
; The TI manual calls the same bits by other names, so the modes are written as nibbles or as
; register bits.
;
; Scene formulas, shared with tests/fixtures/legacy.c (written once, here):
;   name(col, row)       = (32 * row + col) & 255                 768 names
;   g1 pattern(t, r)     = (7 * t + 29 * r) & 255                 tile t, row r
;   g1 colour(g)         = ((5 * g + 1) & 15) << 4 | ((3 * g) & 15), g = t >> 3
;   g2 pattern(idx, r)   = (7 * t + 101 * th + 29 * r) & 255      idx = th * 256 + t, th = 0 to 2
;   g2 colour(idx, r)    = ((5 * t + 3 * th + 3 * r + 1) & 15) << 4 | ((3 * t + 5 * th + 7 * r) & 15)
;   cram(i)              = (13 * i + 5) & 63                      entries 0 to 31
; Colour nibble 0 shows the backdrop (the low nibble of R7, 11). Every nibble value occurs, a
; zero high nibble at g = 3 and a zero low nibble at g = 0. Graphics II tables hold one entry per
; (idx, r), 768 * 8 bytes each, written in that order.
;
; Video memory map, from the TI table addresses (TMS9918A manual 2.4.1 and table 3-2): Graphics I
; name table at (R2 & 15) << 10, pattern generator at (R4 & 7) << 11 and colour table at
; (R3 << 6) & $3FFF; Graphics II pattern table at (R4 & 4) << 11 and colour table at
; (R3 & $80) << 6. R5 puts the sprite table at $3F00, where entry 0 holds Y $D0, which ends the
; list in every mode, so no sprite is drawn.
;   V_G1, V_G2, V_G2_MASKED: names $3800 (R2 $0E), colours $2000, patterns $0000.
;   V_G2_LATE, V_G2_SWITCH: the registers must suit mode 4 and Graphics II together. Graphics II
;   colours at $0000 (R3 $7F), patterns at $2000 (R4 $07), names at $3C00 (R2 $0F, which mode 4
;   reads as $3800), so the mode 4 tile data at tile $C0 (the zero tile at $1800) lies between
;   the tables. R3 $7F and R4 $07 mask nothing on the Master System 1 in either mode.
;   V_G2_SWITCH draws mode 4 names only for rows 0 to 11 ($3800 to $3AFF), so the switch line
;   must be before line 96. V_G2_LATE puts the mode 4 names at $1800 (R2 $06) and the zero tile
;   at $1E00 (tile $F0), then writes R2 $0F and R0 $02 in vertical blank.
.INCLUDE "header.inc"
.IFDEF V_G1
.DEFINE LEGACY_G1 1
.DEFINE NAMES_AT $3800
.DEFINE R0_VALUE $00
.DEFINE R1_VALUE $C0
.ENDIF
.IFDEF V_G2
.DEFINE LEGACY_G2 1
.DEFINE NAMES_AT $3800
.DEFINE PATTERNS_AT $0000
.DEFINE COLOURS_AT $2000
.DEFINE R0_VALUE $02
.DEFINE R1_VALUE $C0
.ENDIF
.IFDEF V_G2_MASKED
.DEFINE LEGACY_G2 1
.DEFINE NAMES_AT $3800
.DEFINE PATTERNS_AT $0000
.DEFINE COLOURS_AT $2000
.DEFINE R0_VALUE $02
.DEFINE R1_VALUE $C0
.ENDIF
.IFDEF V_G2_LATE
.DEFINE LEGACY_G2 1
.DEFINE NAMES_AT $3C00
.DEFINE PATTERNS_AT $2000
.DEFINE COLOURS_AT $0000
.DEFINE R0_VALUE $04
.DEFINE R1_VALUE $E0
.DEFINE INTERRUPTS 1
.ENDIF
.IFDEF V_G2_SWITCH
.DEFINE LEGACY_G2 1
.DEFINE NAMES_AT $3C00
.DEFINE PATTERNS_AT $2000
.DEFINE COLOURS_AT $0000
.DEFINE R0_VALUE $16
.DEFINE R1_VALUE $E0
.DEFINE INTERRUPTS 1
.ENDIF
.IFNDEF NAMES_AT
.FAIL "legacy_modes: define one image variant, for example -D V_G1=1"
.ENDIF
.BANK 0 SLOT 0
.ORG 0
    di
    ld sp,$DFF0
    jp main
.IFDEF INTERRUPTS
.ORG $38
    jp irq
.ENDIF
.ORG $66
    retn
main:
    ; Colour RAM: 32 entries, the generated table. In the Master System video mode the SMS and
    ; the Game Gear read the six-bit values the same way.
    xor a
    out ($BF),a
    ld a,$C0
    out ($BF),a
    ld e,5
    ld b,32
cram_loop:
    ld a,e
    and 63
    out ($BE),a
    ld a,e
    add a,13
    ld e,a
    djnz cram_loop

    ; Names: the counter 0 to 255 three times.
    ld hl,NAMES_AT
    call vram_write_at
    ld c,3
names_third:
    xor a
    ld b,0
names_loop:
    out ($BE),a
    inc a
    djnz names_loop
    dec c
    jr nz,names_third

.IFDEF LEGACY_G1
    ; Patterns at $0000: 256 tiles of 8 rows, byte (7 t + 29 r) & 255.
    ld hl,$0000
    call vram_write_at
    ld e,0
    ld d,0
pattern_tile:
    ld a,e
    ld b,8
pattern_row:
    out ($BE),a
    add a,29
    djnz pattern_row
    ld a,e
    add a,7
    ld e,a
    dec d
    jr nz,pattern_tile

    ; Colours at $2000: 32 groups, high nibble (5 g + 1) & 15, low nibble (3 g) & 15.
    ld hl,$2000
    call vram_write_at
    ld d,0
colour_group:
    ld a,d
    add a,a
    add a,a
    add a,d
    inc a
    and 15
    add a,a
    add a,a
    add a,a
    add a,a
    ld e,a
    ld a,d
    add a,a
    add a,d
    and 15
    or e
    out ($BE),a
    inc d
    ld a,d
    cp 32
    jr nz,colour_group
.ENDIF

.IFDEF LEGACY_G2
    ; Pattern table: three thirds of 256 tiles of 8 rows, byte (7 t + 101 th + 29 r) & 255.
    ld hl,PATTERNS_AT
    call vram_write_at
    ld c,3
    ld h,0
pattern_third:
    ld e,h
    ld d,0
pattern_tile:
    ld a,e
    ld b,8
pattern_row:
    out ($BE),a
    add a,29
    djnz pattern_row
    ld a,e
    add a,7
    ld e,a
    dec d
    jr nz,pattern_tile
    ld a,h
    add a,101
    ld h,a
    dec c
    jr nz,pattern_third

    ; Colour table: the same order, high nibble (5 t + 3 th + 3 r + 1) & 15, low nibble
    ; (3 t + 5 th + 7 r) & 15. $C000 the tile count, $C001 and $C002 the high and low nibble of
    ; row 0 for the tile, $C003 the third, $C004 and $C005 their values at tile 0 of the third.
    ld hl,COLOURS_AT
    call vram_write_at
    xor a
    ld ($C003),a
    inc a
    ld ($C004),a
    xor a
    ld ($C005),a
colour_third:
    ld a,($C004)
    ld ($C001),a
    ld a,($C005)
    ld ($C002),a
    xor a
    ld ($C000),a
colour_tile:
    ld a,($C001)
    ld c,a
    ld a,($C002)
    ld d,a
    ld b,8
colour_row:
    ld a,c
    and 15
    add a,a
    add a,a
    add a,a
    add a,a
    ld e,a
    ld a,d
    and 15
    or e
    out ($BE),a
    ld a,c
    add a,3
    ld c,a
    ld a,d
    add a,7
    ld d,a
    djnz colour_row
    ld a,($C001)
    add a,5
    ld ($C001),a
    ld a,($C002)
    add a,3
    ld ($C002),a
    ld a,($C000)
    inc a
    ld ($C000),a
    jr nz,colour_tile
    ld a,($C004)
    add a,3
    ld ($C004),a
    ld a,($C005)
    add a,5
    ld ($C005),a
    ld a,($C003)
    inc a
    ld ($C003),a
    cp 3
    jr nz,colour_third
.ENDIF

.IFDEF V_G2_SWITCH
    ; Mode 4 names for rows 0 to 11 at $3800: the zero tile $C0, as the word $00C0.
    ld hl,$3800
    call vram_write_at
    ld c,192
mode4_names:
    ld a,$C0
    out ($BE),a
    xor a
    out ($BE),a
    ld a,$C0
    out ($BE),a
    xor a
    out ($BE),a
    dec c
    jr nz,mode4_names
    ld hl,$1800
    call vram_write_at
    ld b,32
    xor a
zero_tile_switch:
    out ($BE),a
    djnz zero_tile_switch
.ENDIF

.IFDEF V_G2_LATE
    ; Mode 4 names, 24 rows of 32 words at $1800: the zero tile $F0 (at $1E00), then the tile.
    ld hl,$1800
    call vram_write_at
    ld bc,768
mode4_names:
    ld a,$F0
    out ($BE),a
    xor a
    out ($BE),a
    dec bc
    ld a,b
    or c
    jr nz,mode4_names
    ld hl,$1E00
    call vram_write_at
    ld b,32
    xor a
zero_tile_late:
    out ($BE),a
    djnz zero_tile_late
.ENDIF

    ; Sprite table: Y $D0 at entry 0.
    ld hl,$3F00
    call vram_write_at
    ld a,$D0
    out ($BE),a

    ; Registers R2 to R10, then R0, then R1 with the display on.
    ld hl,registers
    ld b,9
    ld c,$82
register_loop:
    ld a,(hl)
    out ($BF),a
    ld a,c
    out ($BF),a
    inc hl
    inc c
    djnz register_loop
    ld a,R0_VALUE
    out ($BF),a
    ld a,$80
    out ($BF),a
.IFDEF INTERRUPTS
    ; The frame interrupt counts frames in $C200 (word); the switch is made once, flag $C202.
    ld hl,0
    ld ($C200),hl
    xor a
    ld ($C202),a
    im 1
    ei
.ENDIF
    ld a,R1_VALUE
    out ($BF),a
    ld a,$81
    out ($BF),a

.IFDEF V_G2_SWITCH
    ; Idle: everything happens in the interrupt handler.
forever:
    halt
    jr forever
; The frame interrupt (status bit 7) restores mode 4 in vertical blank. The line interrupt on
; line 47 is taken from line 47's tick 608 on and writes R0 in line 48: Graphics II (nibble 2),
; with the line interrupt enable clear so it fires once a frame.
irq:
    push af
    in a,($BF)
    bit 7,a
    jr z,line_interrupt
    ld a,$16
    out ($BF),a
    ld a,$80
    out ($BF),a
    jr irq_done
line_interrupt:
    ld a,$02
    out ($BF),a
    ld a,$80
    out ($BF),a
irq_done:
    pop af
    ei
    reti
.ELSE
.IFDEF V_G2_LATE
    ; The frame handler counts frames; after the 600th the main loop switches to Graphics II
    ; inside the vertical blank the handler ran in: R2 $0F (names at $3C00) and R0 $02.
late_wait:
    halt
    ld a,($C202)
    or a
    jr nz,late_wait
    ld hl,($C200)
    ld de,600
    or a
    sbc hl,de
    jr c,late_wait
    ld a,$0F
    out ($BF),a
    ld a,$82
    out ($BF),a
    ld a,$02
    out ($BF),a
    ld a,$80
    out ($BF),a
    ld a,1
    ld ($C202),a
    jr late_wait
irq:
    push af
    push hl
    in a,($BF)
    ld hl,($C200)
    inc hl
    ld ($C200),hl
    pop hl
    pop af
    ei
    reti
.ELSE
forever:
    jr forever
.ENDIF
.ENDIF

; HL = video memory address: the data port writes that follow go there.
vram_write_at:
    ld a,l
    out ($BF),a
    ld a,h
    or $40
    out ($BF),a
    ret

; R2 to R10. R7 low nibble 11 is the backdrop colour; R6 is unused here. R8 and R9 scroll nothing.
; R10 is the line interrupt counter: $FF never fires in the active picture, 47 fires on line 47.
registers:
.IFDEF V_G1
    .DB $0E,$80,$00,$7E,$03,$0B,$00,$00,$FF
.ENDIF
.IFDEF V_G2
    .DB $0E,$FF,$03,$7E,$03,$0B,$00,$00,$FF
.ENDIF
.IFDEF V_G2_MASKED
    .DB $0E,$9F,$00,$7E,$03,$0B,$00,$00,$FF
.ENDIF
.IFDEF V_G2_LATE
    .DB $06,$7F,$07,$7E,$03,$0B,$00,$00,$FF
.ENDIF
.IFDEF V_G2_SWITCH
    .DB $0F,$7F,$07,$7E,$03,$0B,$00,$00,$2F
.ENDIF
