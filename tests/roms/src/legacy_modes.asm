; Owned Graphics I scene (MIT). A Z80 program that loads a generated Graphics I
; picture into video memory, programs the registers and idles. It records
; nothing and judges nothing: tests/fixtures/legacy.c holds the closed form
; picture and the runner's frame hash must equal its digest. The image is
; selected by a -D define, one per image (tests/fixtures/tests.cmake).
;
; Fault prevented: a legacy background drawn from the wrong table address, the
; wrong colour nibble or the wrong backdrop, which an oracle written from the
; same address arithmetic as the renderer would also get wrong. Every table
; here is generated by loops from the formulas below, in the tile-index domain;
; the oracle never does address arithmetic.
;
; Mode names. The mode nibble is R0 bit 2, R1 bit 4, R0 bit 1, R1 bit 3 (SMS
; Power naming M4 M3 M2 M1). Graphics I is nibble 0 (R0 bits 1 and 2 clear, R1
; bits 3 and 4 clear). The display is R1 bit 6 and the TI manual calls the same
; bits by other names, so the modes are written as nibbles or register bits.
;
; Scene formulas, shared with tests/fixtures/legacy.c (written once, here):
;   name(col, row)       = (32 * row + col) & 255            768 names
;   g1 pattern(t, r)     = (7 * t + 29 * r) & 255            tile t, row r
;   g1 colour(g)         = ((5 * g + 1) & 15) << 4 | ((3 * g) & 15), g = t >> 3
;   cram(i)              = (13 * i + 5) & 63                 entries 0 to 31
; Colour nibble 0 shows the backdrop (the low nibble of R7). Every nibble value
; occurs, a zero high nibble at g = 3 and a zero low nibble at g = 0.
;
; Video memory map, from the TI table addresses (TMS9918A manual 2.4.1): the
; name table at (R2 & 15) << 10, the pattern generator at (R4 & 7) << 11 and the
; colour table at (R3 << 6) & $3FFF. R5 puts the sprite table at $3F00, where
; entry 0 holds Y $D0, which ends the list in every mode, so no sprite is drawn.
;   R2 $0E names $3800    R3 $80 colours $2000    R4 $00 patterns $0000
;   R5 $7E sprite table $3F00
.INCLUDE "header.inc"
.IFNDEF V_G1
.FAIL "legacy_modes: define one image variant with -D V_G1=1"
.ENDIF
.BANK 0 SLOT 0
.ORG 0
    di
    ld sp,$DFF0
    jp main
.ORG $66
    retn
main:
    ; Colour RAM: 32 entries, the generated table. In the Master System video
    ; mode the SMS and the Game Gear read the six-bit values the same way.
    xor a
    out ($BF),a
    ld a,$C0
    out ($BF),a
    ld e,5
    ld b,32
cram_loop:
    ld a,e
    and 63
    out ($BE),a
    ld a,e
    add a,13
    ld e,a
    djnz cram_loop

    ; Names: the counter 0 to 255 three times, at $3800.
    ld hl,$3800
    call vram_write_at
    ld c,3
names_third:
    xor a
    ld b,0
names_loop:
    out ($BE),a
    inc a
    djnz names_loop
    dec c
    jr nz,names_third

    ; Patterns at $0000: 256 tiles of 8 rows, byte (7 t + 29 r) & 255.
    ld hl,$0000
    call vram_write_at
    ld e,0
    ld d,0
pattern_tile:
    ld a,e
    ld b,8
pattern_row:
    out ($BE),a
    add a,29
    djnz pattern_row
    ld a,e
    add a,7
    ld e,a
    dec d
    jr nz,pattern_tile

    ; Colours at $2000: 32 groups, high nibble (5 g + 1) & 15, low nibble (3 g) & 15.
    ld hl,$2000
    call vram_write_at
    ld d,0
colour_group:
    ld a,d
    add a,a
    add a,a
    add a,d
    inc a
    and 15
    add a,a
    add a,a
    add a,a
    add a,a
    ld e,a
    ld a,d
    add a,a
    add a,d
    and 15
    or e
    out ($BE),a
    inc d
    ld a,d
    cp 32
    jr nz,colour_group

    ; Sprite table: Y $D0 at entry 0.
    ld hl,$3F00
    call vram_write_at
    ld a,$D0
    out ($BE),a

    ; Registers R2 to R10, then R0, then R1 with the display on.
    ld hl,registers
    ld b,9
    ld c,$82
register_loop:
    ld a,(hl)
    out ($BF),a
    ld a,c
    out ($BF),a
    inc hl
    inc c
    djnz register_loop
    ld a,$00
    out ($BF),a
    ld a,$80
    out ($BF),a
    ld a,$C0
    out ($BF),a
    ld a,$81
    out ($BF),a
forever:
    jr forever

; HL = video memory address: the data port writes that follow go there.
vram_write_at:
    ld a,l
    out ($BF),a
    ld a,h
    or $40
    out ($BF),a
    ret

; R2 to R10. R7 low nibble 11 is the backdrop colour; R6 is unused here.
registers:
    .DB $0E,$80,$00,$7E,$03,$0B,$00,$00,$FF
