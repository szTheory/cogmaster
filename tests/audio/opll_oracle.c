/* One-shot oracle for the YM2413 port. It is built by hand against the unmodified
   emu2413 fetched at the pinned commit, and is not part of the test suite
   because its upstream is fetched on demand:

     scripts/fetch-pin.sh emu2413-c build/pins/emu2413
     scripts/fetch-pin.sh emu2413-h build/pins/emu2413
     cc -std=c17 -O2 -Isrc -Itests/audio -Ibuild/pins/emu2413 tests/audio/opll_oracle.c \
        src/opll.c src/opll_reg.c -lm -o build/opll-oracle

   Modes:
     tables      print src/opll_tables.inc; exit 1 if the integer key-scale table differs
                 from the original's floating point one
     stream N    run the original over the seeded register stream for N samples and print
                 "samples N seed S sha256 H" over the 16-bit samples, little-endian
     compare N   run the original and the port over the same stream; exit 1 at the first
                 sample, or channel output, that differs and print its index

   The chip clock is exactly 72 times the sample rate, so each OPLL_calc runs one update
   and the original's rate converter stays off. Floating point is allowed here. */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "emu2413.c"
#include "../../runner/sha256.c"
#include "opll.h"
#include "opll_stream.h"

#define RATE 49716u
#define CLOCK (RATE * 72u)

/* The kl_table of the original in eighths of a step: the integer the port uses. */
static const int kl8[16] = {0,   144, 192, 222, 240, 258, 270, 282,
                            288, 300, 306, 312, 318, 324, 330, 336};

static const char *const tone_names[15] = {"Violin",
                                           "Guitar",
                                           "Piano",
                                           "Flute",
                                           "Clarinet",
                                           "Oboe",
                                           "Trumpet",
                                           "Organ",
                                           "Horn",
                                           "Synthesizer",
                                           "Harpsichord",
                                           "Vibraphone",
                                           "Synthesizer Bass",
                                           "Acoustic Bass",
                                           "Electric Guitar"};

static void put_u16(const char *type, const char *name, const uint16_t *v, size_t n)
{
    printf("static const %s %s[%zu] = {", type, name, n);
    for (size_t i = 0; i < n; i++) {
        printf("%s%u,", i % 16 == 0 ? "\n    " : " ", (unsigned)v[i]);
    }
    printf("\n};\n\n");
}

static void put_u8_2d(const char *type, const char *name, const uint8_t *v, size_t rows,
                      size_t cols)
{
    printf("static const %s %s[%zu][%zu] = {\n", type, name, rows, cols);
    for (size_t r = 0; r < rows; r++) {
        printf("    {");
        for (size_t c = 0; c < cols; c++) {
            printf("%s%u", c ? ", " : "", (unsigned)v[r * cols + c]);
        }
        printf("},\n");
    }
    printf("};\n\n");
}

static int tables(void)
{
    OPLL *o = OPLL_new(CLOCK, RATE);
    uint16_t tll[128][4];
    uint16_t exp_copy[256];
    uint8_t ml[16];
    uint8_t am[210];
    int bad = 0;

    for (int fnum = 0; fnum < 16; fnum++) {
        for (int block = 0; block < 8; block++) {
            for (int kl = 0; kl < 4; kl++) {
                int v = 0;
                if (kl != 0) {
                    int tmp = (kl8[fnum] - 48 * (7 - block)) / 8;
                    if (tmp > 0) {
                        v = ((tmp >> (3 - kl)) * 8) / 3;
                    }
                }
                tll[(block << 4) | fnum][kl] = (uint16_t)v;
                if (tll_table[(block << 4) | fnum][kl] != v) {
                    fprintf(stderr, "tll[%d][%d]: integer %d, original %u\n", (block << 4) | fnum,
                            kl, v, (unsigned)tll_table[(block << 4) | fnum][kl]);
                    bad = 1;
                }
            }
        }
    }
    if (bad) {
        OPLL_delete(o);
        return 1;
    }

    printf("/* Generated by tests/audio/opll_oracle.c tables from emu2413 at commit\n"
           "   a1d5120903b75f93d3eb7690e34a29c0b4add903; do not edit. Each group is included by\n"
           "   the source file that uses it, so no file sees a table it does not use. The key\n"
           "   scale table comes from the integer formula ((d >> (3 - level)) * 8) / 3 and was\n"
           "   compared entry by entry with the original's floating point table. */\n\n");

    printf("#ifdef OPLL_WANT_WAVES\n\n");
    for (int i = 0; i < 256; i++) {
        exp_copy[i] = exp_table[i];
    }
    printf("/* round((2^(x/256) - 1) * 1024) */\n");
    put_u16("uint16_t", "exp_table", exp_copy, 256);
    printf("/* Full sine as an attenuation, -log2(sin) in steps of 1/256 over a mirrored quarter\n"
           "   wave, with bit 15 set on the negative half. */\n");
    put_u16("uint16_t", "fullsin_table", fullsin_table, 1024);
    printf("/* Half sine: the positive half of the full sine, then the largest attenuation. */\n");
    put_u16("uint16_t", "halfsin_table", halfsin_table, 1024);
    printf("/* Pitch modulation offsets by the top three f-number bits and the LFO step. */\n");
    printf("static const int8_t pm_table[8][8] = {\n");
    for (int r = 0; r < 8; r++) {
        printf("    {");
        for (int c = 0; c < 8; c++) {
            printf("%s%d", c ? ", " : "", (int)pm_table[r][c]);
        }
        printf("},\n");
    }
    printf("};\n\n");
    for (int i = 0; i < 210; i++) {
        am[i] = am_table[i];
    }
    printf("/* Amplitude LFO levels, each held for 64 samples. */\n");
    printf("static const uint8_t am_table[210] = {");
    for (int i = 0; i < 210; i++) {
        printf("%s%u,", i % 16 == 0 ? "\n    " : " ", (unsigned)am[i]);
    }
    printf("\n};\n\n");
    printf("/* Envelope step patterns by rate remainder. */\n");
    put_u8_2d("uint8_t", "eg_step_tables", &eg_step_tables[0][0], 4, 8);
    for (int i = 0; i < 16; i++) {
        ml[i] = (uint8_t)ml_table[i];
    }
    printf("/* Frequency multiples, doubled so that one half is a whole number. */\n");
    printf("static const uint8_t ml_table[16] = {");
    for (int i = 0; i < 16; i++) {
        printf("%s%u,", i ? " " : "", (unsigned)ml[i]);
    }
    printf("};\n\n");
    printf("/* Key scale level by block and top four f-number bits, then by level, in envelope\n"
           "   steps. */\n");
    printf("static const uint16_t tll_table[128][4] = {\n");
    for (int r = 0; r < 128; r++) {
        printf("    {%u, %u, %u, %u},\n", (unsigned)tll[r][0], (unsigned)tll[r][1],
               (unsigned)tll[r][2], (unsigned)tll[r][3]);
    }
    printf("};\n\n");
    printf("/* Key scale offset by block and f-number bit 8, then by the key scale flag. */\n");
    printf("static const uint8_t rks_table[16][2] = {\n");
    for (int r = 0; r < 16; r++) {
        printf("    {%d, %d},\n", (int)rks_table[r][0], (int)rks_table[r][1]);
    }
    printf("};\n\n#endif\n\n");

    printf("#ifdef OPLL_WANT_VOICES\n\n");
    printf("/* The YM2413 instrument ROM: user, fifteen instruments, then the rhythm voices, as\n"
           "   eight-byte patch dumps. The upstream header credits andete's YM2413 notes for the\n"
           "   instrument data, and the rhythm rows come from the VRC7 patch set. */\n");
    printf("static const uint8_t default_inst[19 * 8] = {\n");
    for (int r = 0; r < 19; r++) {
        const char *name = r == 0 ? "user" : r < 16 ? tone_names[r - 1] : "rhythm";
        printf("    ");
        for (int c = 0; c < 8; c++) {
            printf("0x%02x,%s", (unsigned)default_inst[0][r * 8 + c], c < 7 ? " " : "");
        }
        printf(" /* %s */\n", name);
    }
    printf("};\n\n#endif\n");
    OPLL_delete(o);
    return 0;
}

static int run_stream(uint32_t n)
{
    OPLL *o = OPLL_new(CLOCK, RATE);
    struct opll_stream st;
    cogmaster__sha256 h;
    uint8_t digest[32];
    char hex[65];
    uint32_t reg;
    uint32_t val;

    opll_stream_init(&st, OPLL_STREAM_SEED);
    cogmaster__sha256_init(&h);
    for (uint32_t i = 0; i < n; i++) {
        if (opll_stream_step(&st, &reg, &val)) {
            OPLL_writeReg(o, reg, (uint8_t)val);
        }
        uint16_t s = (uint16_t)OPLL_calc(o);
        uint8_t b[2] = {(uint8_t)(s & 0xffu), (uint8_t)(s >> 8)};
        cogmaster__sha256_update(&h, b, 2);
    }
    cogmaster__sha256_final(&h, digest);
    cogmaster__sha256_hex(digest, hex);
    printf("samples %u seed 0x%016llx sha256 %s\n", (unsigned)n,
           (unsigned long long)OPLL_STREAM_SEED, hex);
    OPLL_delete(o);
    return 0;
}

static int compare(uint32_t n)
{
    OPLL *o = OPLL_new(CLOCK, RATE);
    static struct cogmaster__opll port;
    struct opll_stream st;
    uint32_t reg;
    uint32_t val;

    cogmaster__opll_reset(&port);
    opll_stream_init(&st, OPLL_STREAM_SEED);
    for (uint32_t i = 0; i < n; i++) {
        if (opll_stream_step(&st, &reg, &val)) {
            OPLL_writeReg(o, reg, (uint8_t)val);
            cogmaster__opll_write(&port, reg, val);
        }
        int32_t want = OPLL_calc(o);
        int32_t got = cogmaster__opll_sample(&port);
        int differ = want != got;
        for (int c = 0; c < 14; c++) {
            differ |= o->ch_out[c] != port.ch_out[c];
        }
        if (differ) {
            fprintf(stderr, "compare: first difference at sample %u: original %d, port %d\n",
                    (unsigned)i, (int)want, (int)got);
            OPLL_delete(o);
            return 1;
        }
    }
    printf("compare: %u samples equal\n", (unsigned)n);
    OPLL_delete(o);
    return 0;
}

int main(int argc, char **argv)
{
    if (argc == 2 && strcmp(argv[1], "tables") == 0) {
        return tables();
    }
    if (argc == 3 && strcmp(argv[1], "stream") == 0) {
        return run_stream((uint32_t)strtoul(argv[2], NULL, 10));
    }
    if (argc == 3 && strcmp(argv[1], "compare") == 0) {
        return compare((uint32_t)strtoul(argv[2], NULL, 10));
    }
    fprintf(stderr, "usage: opll-oracle tables | stream N | compare N\n");
    return 2;
}
