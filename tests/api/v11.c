/* API v11: the board constant for the Sega board with a 93C46 save chip and the three version
   numbers. Every name the version adds is used here. */
#include "cogmaster.h"
#include "../check.h"

int main(void)
{
    CHECK_EQ_U64(COGMASTER_API_VERSION, 11u);
    CHECK_EQ_U64(COGMASTER_ABI_VERSION, 1u);
    CHECK_EQ_U64(COGMASTER_BEHAVIOUR_REVISION, 13u);
    CHECK_EQ_U64(COGMASTER_STATE_FORMAT_VERSION, 13u);

    cogmaster_versions v;
    CHECK(cogmaster_get_versions(&v) == COGMASTER_STATUS_OK);
    CHECK_EQ_U64(v.api, 11u);
    CHECK_EQ_U64(v.behaviour, 13u);
    CHECK_EQ_U64(v.state, 13u);

    CHECK_EQ_U64(COGMASTER_BOARD_SEGA_EEPROM, 10u);
    CHECK(COGMASTER_BOARD_SEGA_EEPROM != COGMASTER_BOARD_ROM_ONLY);
    CHECK(COGMASTER_BOARD_SEGA_EEPROM != COGMASTER_BOARD_SEGA);
    CHECK(COGMASTER_BOARD_SEGA_EEPROM != COGMASTER_BOARD_CODEMASTERS);
    CHECK(COGMASTER_BOARD_SEGA_EEPROM != COGMASTER_BOARD_KOREAN);
    CHECK(COGMASTER_BOARD_SEGA_EEPROM != COGMASTER_BOARD_KOREAN_NB);
    CHECK(COGMASTER_BOARD_SEGA_EEPROM != COGMASTER_BOARD_HICOM);
    CHECK(COGMASTER_BOARD_SEGA_EEPROM != COGMASTER_BOARD_ZEMINA);
    CHECK(COGMASTER_BOARD_SEGA_EEPROM != COGMASTER_BOARD_NEMESIS);
    CHECK(COGMASTER_BOARD_SEGA_EEPROM != COGMASTER_BOARD_4PAK);
    CHECK_DONE();
}
