/* In-process oracles for the Graphics I and II draw, checked against hand-computed literals.

   The oracles take a register set and a generated scene and return the expected RGB444 dot
   (0BBBBGGGGRRRR). They never read video memory and never compute an address: the scene is a
   function of tile numbers, pattern rows and colour groups, the formulas of
   tests/roms/src/legacy_modes.asm. A renderer test loads the same generated bytes at the table
   addresses the registers select and compares the renderer with these functions; the literal
   table here is what keeps the oracles honest before any renderer exists.

   Model choices, each labelled where it is made: the Graphics II address masks, the sprite top line
   for Y at or past $E0, the colour 0 collision and the fifth sprite index. A fixture proves
   fidelity to these notes, not to silicon. */
#include <stdint.h>
#include <stdlib.h>
#include <string.h>
#include "internal.h"
#include "z80.h"
#include "../check.h"

enum profile { PROFILE_SMS1, PROFILE_SMS2, PROFILE_GG, PROFILE_COUNT };

#define FIELD_W 256u
#define FIELD_H 192u
#define BACKDROP_NIBBLE 11u

/* Six-bit BBGGRR to RGB444 words: each two-bit channel c becomes c * 5. */
static uint16_t rgb444(uint32_t six)
{
    uint32_t r = six & 3u, g = (six >> 2) & 3u, b = (six >> 4) & 3u;
    return (uint16_t)((b * 5u) << 8 | (g * 5u) << 4 | (r * 5u));
}

/* The Master System fixed palette (SMS Power palette page). Model: no source measures the
   Sega chip's legacy palette, and the sources disagree about the Game Gear. */
static const uint8_t fixed_palette[16] = {0x00, 0x00, 0x08, 0x0C, 0x10, 0x30, 0x01, 0x3C,
                                          0x02, 0x03, 0x05, 0x0F, 0x04, 0x33, 0x15, 0x3F};

/* The colour RAM the scene writes: entry i holds (13 i + 5) & 63. Game Gear in Master System
   video mode reads entry 16 + n for palette entry n (msvdp section 14; a model). */
static uint32_t cram_value(uint32_t i)
{
    return (13u * i + 5u) & 63u;
}

static uint16_t oracle_palette(enum profile p, uint32_t n)
{
    n &= 15u;
    return p == PROFILE_GG ? rgb444(cram_value(16u + n)) : rgb444(fixed_palette[n]);
}

/* The generated scene, by tile (the formulas in legacy_modes.asm). */
static uint32_t scene_name(uint32_t col, uint32_t row)
{
    return (32u * row + col) & 255u;
}

static uint16_t nibble_dot(enum profile p, uint32_t pattern, uint32_t colour, uint32_t x)
{
    uint32_t nibble = (pattern >> (7u - (x & 7u))) & 1u ? colour >> 4 : colour & 15u;
    return oracle_palette(p, nibble == 0u ? BACKDROP_NIBBLE : nibble);
}

/* Graphics I: pattern (7 t + 29 r) & 255, colour byte ((5 g + 1) & 15) << 4 | (3 g) & 15 for the
   group g = t >> 3. */
static uint16_t oracle_g1(enum profile p, uint32_t x, uint32_t y)
{
    uint32_t t = scene_name(x >> 3, y >> 3), r = y & 7u, g = t >> 3;
    uint32_t pattern = (7u * t + 29u * r) & 255u;
    uint32_t colour = ((5u * g + 1u) & 15u) << 4 | ((3u * g) & 15u);
    return nibble_dot(p, pattern, colour, x);
}

/* Graphics II: idx = third * 256 + name, third = row / 8. Pattern (7 t + 101 th + 29 r) & 255 and
   colour ((5 t + 3 th + 3 r + 1) & 15) << 4 | (3 t + 5 th + 7 r) & 15, t = idx & 255, th = idx
   >> 8. Model: the Master System 1 ANDs idx with ((R4 & 3) << 8) | 255 for the pattern and with
   ((R3 & 127) << 3) | 7 for the colour (Sean Young's TMS9918A notes: the TI manual's all-ones
   low bits act as a mask on the index); the Master System 2 and Game Gear in Master System
   mode do not mask (msvdp, a model with about 60 percent confidence). The masks are not read
   from any table address. */
static uint32_t g2_pattern(uint32_t idx, uint32_t r)
{
    return (7u * (idx & 255u) + 101u * (idx >> 8) + 29u * r) & 255u;
}
static uint32_t g2_colour(uint32_t idx, uint32_t r)
{
    uint32_t t = idx & 255u, th = idx >> 8;
    return ((5u * t + 3u * th + 3u * r + 1u) & 15u) << 4 | ((3u * t + 5u * th + 7u * r) & 15u);
}
static uint16_t oracle_g2(enum profile p, uint32_t r3, uint32_t r4, uint32_t x, uint32_t y)
{
    uint32_t row = y >> 3, r = y & 7u;
    uint32_t idx = (row >> 3) << 8 | scene_name(x >> 3, row), pidx = idx, cidx = idx;
    if (p == PROFILE_SMS1) {
        pidx &= ((r4 & 3u) << 8) | 255u;
        cidx &= ((r3 & 127u) << 3) | 7u;
    }
    return nibble_dot(p, g2_pattern(pidx, r), g2_colour(cidx, r), x);
}

/* Legacy sprites, a per-line walk of the attribute table in index order, never the slot
   structure. 32 entries of Y, X, name and attribute (bit 7 early clock, bits 3..0 colour); a Y of
   $D0 ends the list whatever its position (every source agrees). R1 bit 1 is 16 by 16, bit 0
   magnified. Four sprites a line, lower index wins, colour 0 transparent. Y at or past $E0 is
   negative: the top line is Y - 255, otherwise Y + 1 (model: ares and the TI manual's range read
   that way, MAME's TMS file uses > $E0 and its SMS path >= $F0). The early clock bit moves the
   sprite 32 dots left (R0 bit 3 does nothing in the legacy modes; a model). The patterns are
   generated by name n and row r: name 0 blank, 1 solid, 2 the left column, 3 the right column,
   4 columns 1 to 7, and (53 n + 17 r + 1) & 255 for any other name. */
struct sprite {
    uint8_t y, x, name, attr;
};
struct scene {
    uint32_t r1, count;
    struct sprite e[12];
};
struct sprite_dot {
    uint32_t colour;      /* the winning colour, 0 for none */
    uint32_t coincidence; /* two of the shown sprites have a set pattern bit at this dot */
};

static uint32_t pattern_byte(uint32_t name, uint32_t r)
{
    switch (name) {
    case 0u:
        return 0u;
    case 1u:
        return 255u;
    case 2u:
        return 128u;
    case 3u:
        return 1u;
    case 4u:
        return 127u;
    default:
        return (53u * name + 17u * r + 1u) & 255u;
    }
}

static int sprite_bit(const struct scene *s, const struct sprite *e, int line, int x)
{
    int size = (s->r1 & 2u) != 0u ? 16 : 8, mag = (s->r1 & 1u) != 0u ? 2 : 1, span = size * mag;
    int top = e->y >= 0xE0u ? (int)e->y - 255 : (int)e->y + 1;
    int left = (int)e->x - ((e->attr & 0x80u) != 0u ? 32 : 0);
    int dx = x - left, dy = line - top;
    if (dx < 0 || dy < 0 || dx >= span || dy >= span)
        return 0;
    uint32_t sx = (uint32_t)(dx / mag), sy = (uint32_t)(dy / mag), name = e->name;
    if (size == 16)
        name = (name & 0xFCu) + (sx >> 3) * 2u + (sy >> 3);
    return (int)((pattern_byte(name, sy & 7u) >> (7u - (sx & 7u))) & 1u);
}

static struct sprite_dot oracle_sprites(const struct scene *s, uint32_t line, uint32_t x)
{
    struct sprite_dot dot = {0u, 0u};
    uint32_t shown = 0u, set = 0u;
    int span = ((s->r1 & 2u) != 0u ? 16 : 8) * ((s->r1 & 1u) != 0u ? 2 : 1);
    for (uint32_t i = 0u; i < s->count && i < 32u && s->e[i].y != 0xD0u && shown < 4u; i++) {
        int top = s->e[i].y >= 0xE0u ? (int)s->e[i].y - 255 : (int)s->e[i].y + 1;
        if ((int)line < top || (int)line >= top + span)
            continue;
        shown++;
        if (sprite_bit(s, &s->e[i], (int)line, (int)x)) {
            set++;
            if (dot.colour == 0u)
                dot.colour = s->e[i].attr & 15u;
        }
    }
    dot.coincidence = set >= 2u;
    return dot;
}

/* Whether any dot 0 to 255 of the line has a coincidence: dots past 255 do not count (model). */
static uint32_t line_coincidence(const struct scene *s, uint32_t line)
{
    for (uint32_t x = 0u; x < FIELD_W; x++)
        if (oracle_sprites(s, line, x).coincidence != 0u)
            return 1u;
    return 0u;
}

