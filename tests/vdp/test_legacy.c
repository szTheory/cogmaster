static void *alloc(void *u, size_t n)
{
    (void)u;
    return malloc(n);
}
static void release(void *u, void *p, size_t n)
{
    (void)u;
    (void)n;
    free(p);
}

/* An instance with the oracle's colour RAM (entries 0 to 31, six-bit values; the Game Gear in
   Master System video mode reads 16 + n from the same bytes), R7 low nibble 11 and a sprite table
   at $3F00 whose first Y is $D0, so that no sprite exists. Every video memory byte is zero until a
   case loads a scene. */
static cogmaster *make_video(uint32_t machine, uint32_t video)
{
    cogmaster_config cfg = {0};
    cfg.size = sizeof cfg;
    cfg.allocator.alloc = alloc;
    cfg.allocator.free = release;
    cogmaster *m = NULL;
    CHECK_EQ_U64(cogmaster_create(&cfg, &m), COGMASTER_STATUS_OK);
    static const uint8_t image[1024] = {0xF3, 0x76};
    cogmaster_media media = {0};
    media.size = sizeof media;
    media.image = image;
    media.image_size = sizeof image;
    media.machine = machine;
    media.video_mode = video;
    CHECK_EQ_U64(cogmaster_load(m, &media), COGMASTER_STATUS_OK);
    for (uint32_t i = 0u; i < 32u; i++)
        m->vdp.cram[i] = (uint8_t)cram_value(i);
    m->vdp.reg[5] = 0x7Fu;
    m->vdp.reg[7] = BACKDROP_NIBBLE;
    m->vdp.vram[0x3F00] = 0xD0u;
    return m;
}
static cogmaster *make(enum profile p)
{
    static const uint32_t machine[PROFILE_COUNT] = {COGMASTER_MACHINE_SMS1, COGMASTER_MACHINE_SMS2,
                                                    COGMASTER_MACHINE_GG};
    return make_video(machine[p], p == PROFILE_GG ? COGMASTER_VIDEO_SMS : COGMASTER_VIDEO_AUTO);
}

/* R0 to R4 as a game would write them, and the display latch that the next line would take from R1
   bit 6. */
static void regs(cogmaster *m, uint32_t r0, uint32_t r1, uint32_t r2, uint32_t r3, uint32_t r4)
{
    m->vdp.reg[0] = (uint8_t)r0;
    m->vdp.reg[1] = (uint8_t)r1;
    m->vdp.reg[2] = (uint8_t)r2;
    m->vdp.reg[3] = (uint8_t)r3;
    m->vdp.reg[4] = (uint8_t)r4;
    m->vdp.display = (uint8_t)((r1 >> 6) & 1u);
}
static void run(cogmaster *m)
{
    CHECK_EQ_U64(cogmaster_run_frame(m, NULL), COGMASTER_STATUS_OK);
}
static void put(cogmaster *m, uint32_t at, uint32_t value)
{
    m->vdp.vram[at & 0x3FFFu] = (uint8_t)value;
}

/* The scenes of the oracles, placed at the table addresses the registers select (TI TMS9918A manual
   2.4.1 and table 3-2: Graphics I names at (R2 & 15) << 10, patterns at (R4 & 7) << 11, colours at
   (R3 << 6) & $3FFF; Graphics II patterns at (R4 & 4) << 11 and colours at (R3 & $80) << 6). The
   oracle never sees an address; this is the only place the two meet. */
static void scene_names(cogmaster *m, uint32_t r2)
{
    for (uint32_t row = 0u; row < 24u; row++)
        for (uint32_t col = 0u; col < 32u; col++)
            put(m, ((r2 & 15u) << 10) + 32u * row + col, scene_name(col, row));
}
static void scene_g1(cogmaster *m, uint32_t r2, uint32_t r3, uint32_t r4)
{
    scene_names(m, r2);
    for (uint32_t t = 0u; t < 256u; t++)
        for (uint32_t r = 0u; r < 8u; r++)
            put(m, ((r4 & 7u) << 11) + 8u * t + r, (7u * t + 29u * r) & 255u);
    for (uint32_t g = 0u; g < 32u; g++)
        put(m, (r3 << 6) + g, ((5u * g + 1u) & 15u) << 4 | ((3u * g) & 15u));
}
static void scene_g2(cogmaster *m, uint32_t r2, uint32_t r3, uint32_t r4)
{
    scene_names(m, r2);
    for (uint32_t idx = 0u; idx < 768u; idx++) {
        for (uint32_t r = 0u; r < 8u; r++) {
            put(m, ((r4 & 4u) << 11) + 8u * idx + r, g2_pattern(idx, r));
            put(m, ((r3 & 0x80u) << 6) + 8u * idx + r, g2_colour(idx, r));
        }
    }
}

static uint16_t expect(enum profile p, int g2, uint32_t r3, uint32_t r4, uint32_t x, uint32_t y)
{
    return g2 ? oracle_g2(p, r3, r4, x, y) : oracle_g1(p, x, y);
}

/* The dots of lines y0 to y1 - 1 that differ from the oracle; the first is printed. */
static uint32_t mismatches(const cogmaster *m, enum profile p, int g2, uint32_t r3, uint32_t r4,
                           uint32_t y0, uint32_t y1)
{
    uint32_t bad = 0u;
    for (uint32_t y = y0; y < y1; y++) {
        for (uint32_t x = 0u; x < FIELD_W; x++) {
            uint16_t want = expect(p, g2, r3, r4, x, y);
            if (m->field[y][x] != want && bad++ == 0u)
                fprintf(stderr, "profile %d R3 %02x R4 %02x (%u,%u) is %03x, expected %03x\n",
                        (int)p, r3, r4, x, y, m->field[y][x], want);
        }
    }
    return bad;
}

/* Graphics I with the scene at two layouts: the tables low in memory and names high, and the
   colour table at the top of memory, where the 14-bit address mask matters. */
static void g1(void)
{
    static const uint32_t layout[2][3] = {{0x0Eu, 0x80u, 0x00u}, {0x03u, 0xFFu, 0x03u}};
    for (enum profile p = PROFILE_SMS1; p < PROFILE_COUNT; p++) {
        for (size_t k = 0u; k < 2u; k++) {
            cogmaster *m = make(p);
            scene_g1(m, layout[k][0], layout[k][1], layout[k][2]);
            regs(m, 0x00u, 0x40u, layout[k][0], layout[k][1], layout[k][2]);
            run(m);
            CHECK_EQ_U64(mismatches(m, p, 0, 0u, 0u, 0u, FIELD_H), 0u);
            CHECK_EQ_U64(m->fault_present, 0u);
            if (k == 0u) {
                for (size_t i = 0u; i < sizeof g1_cases / sizeof g1_cases[0]; i++)
                    if (g1_cases[i].profile == p)
                        CHECK_EQ_HEX(m->field[g1_cases[i].y][g1_cases[i].x], g1_cases[i].want);
            }
            cogmaster_destroy(m);
        }
        /* Empty edge: all video memory zero is pattern 0 and colour byte 0, so every dot of lines 0
           to 191 is the backdrop, whatever the registers point at. */
        cogmaster *m = make(p);
        regs(m, 0x00u, 0x40u, 0x0Eu, 0x80u, 0x00u);
        run(m);
        uint32_t bad = 0u;
        for (uint32_t y = 0u; y < FIELD_H; y++)
            for (uint32_t x = 0u; x < FIELD_W; x++)
                bad += m->field[y][x] != oracle_palette(p, BACKDROP_NIBBLE);
        CHECK_EQ_U64(bad, 0u);
        CHECK_EQ_U64(m->fault_present, 0u);
        cogmaster_destroy(m);
    }
}

/* One Graphics II frame with the scene at the tables R3 and R4 select, compared with the oracle on
   every dot and with the hand-computed literals for that profile and pair. */
static cogmaster *g2_frame(enum profile p, uint32_t r3, uint32_t r4)
{
    cogmaster *m = make(p);
    scene_g2(m, 0x0Eu, r3, r4);
    regs(m, 0x02u, 0x40u, 0x0Eu, r3, r4);
    run(m);
    CHECK_EQ_U64(mismatches(m, p, 1, r3, r4, 0u, FIELD_H), 0u);
    CHECK_EQ_U64(m->fault_present, 0u);
    for (size_t i = 0u; i < sizeof g2_cases / sizeof g2_cases[0]; i++) {
        const struct dot_case *c = &g2_cases[i];
        if (c->profile == p && c->r3 == r3 && c->r4 == r4)
            CHECK_EQ_HEX(m->field[c->y][c->x], c->want);
    }
    return m;
}

static void g2(void)
{
    for (enum profile p = PROFILE_SMS1; p < PROFILE_COUNT; p++) {
        cogmaster *m = g2_frame(p, 0xFFu, 0x03u);
        /* Adjacency: line 63 ends the first third and line 64 starts the second, line 127 and line
           128 the second and third. The oracle matched above; here the lines are also shown not to
           be the picture of the third before them, so a third taken from the wrong line fails. */
        static const uint32_t edges[2][2] = {{63u, 64u}, {127u, 128u}};
        for (size_t k = 0u; k < 2u; k++) {
            uint32_t from_before = 0u;
            for (uint32_t x = 0u; x < FIELD_W; x++)
                from_before +=
                    m->field[edges[k][1]][x] != oracle_g2(p, 0xFFu, 0x03u, x, edges[k][0]);
            CHECK(from_before > 0u);
            CHECK_EQ_U64(mismatches(m, p, 1, 0xFFu, 0x03u, edges[k][0], edges[k][1] + 1u), 0u);
        }
        cogmaster_destroy(m);
        /* Empty edge: a colour byte of zero shows the backdrop for a set bit and for a clear bit.
           Entry 0 row 0 has all bits set and entry 1 row 0 none; entry 2 row 0 keeps its generated
           colour byte as the control. */
        m = make(p);
        scene_g2(m, 0x0Eu, 0xFFu, 0x03u);
        put(m, 0x0000u, 0xFFu);
        put(m, 0x2000u, 0x00u);
        put(m, 0x0008u, 0x00u);
        put(m, 0x2008u, 0x00u);
        regs(m, 0x02u, 0x40u, 0x0Eu, 0xFFu, 0x03u);
        run(m);
        for (uint32_t x = 0u; x < 16u; x++)
            CHECK_EQ_HEX(m->field[0][x], oracle_palette(p, BACKDROP_NIBBLE));
        CHECK(m->field[0][16] != oracle_palette(p, BACKDROP_NIBBLE));
        cogmaster_destroy(m);
    }
}

/* The sixteen palette entries, by function against the literal table and the oracle, and on screen:
   cell n of line 0 is a solid tile whose colour byte is n in both nibbles. */
static void palette(void)
{
    for (enum profile p = PROFILE_SMS1; p < PROFILE_COUNT; p++) {
        cogmaster *m = make(p);
        for (uint32_t n = 0u; n < 16u; n++)
            CHECK_EQ_HEX(cogmaster__legacy_colour(m, n), oracle_palette(p, n));
        for (size_t i = 0u; i < sizeof palette_cases / sizeof palette_cases[0]; i++)
            if (palette_cases[i].profile == p)
                CHECK_EQ_HEX(cogmaster__legacy_colour(m, palette_cases[i].nibble),
                             palette_cases[i].want);
        for (uint32_t n = 0u; n < 16u; n++) {
            put(m, 0x3800u + n, 8u * n);
            for (uint32_t r = 0u; r < 8u; r++)
                put(m, 8u * (8u * n) + r, 0xFFu);
            put(m, 0x2000u + n, n << 4 | n);
        }
        regs(m, 0x00u, 0x40u, 0x0Eu, 0x80u, 0x00u);
        run(m);
        for (uint32_t n = 0u; n < 16u; n++)
            for (uint32_t x = 8u * n; x < 8u * n + 8u; x++)
                CHECK_EQ_HEX(m->field[0][x], oracle_palette(p, n == 0u ? BACKDROP_NIBBLE : n));
        cogmaster_destroy(m);
    }
}

/* The backdrop of a picture: the legacy palette entry R7 & 15 while the display is on in Graphics I
   or II, the colour RAM entry 16 + (R7 & 15) with the display off, in mode 4 and in a mode that
   faults. Both the function and the frame descriptor value take the same colour. */
static void backdrop(void)
{
    struct config {
        uint32_t r0, r1, legacy;
    };
    static const struct config configs[] = {{0x00u, 0x40u, 1u},
                                            {0x02u, 0x40u, 1u},
                                            {0x00u, 0x00u, 0u},
                                            {0x04u, 0x40u, 0u},
                                            {0x00u, 0x50u, 0u}};
    static const uint32_t r7s[] = {BACKDROP_NIBBLE, 0xA3u, 0x00u};
    for (enum profile p = PROFILE_SMS1; p < PROFILE_COUNT; p++) {
        for (size_t k = 0u; k < sizeof configs / sizeof configs[0]; k++) {
            for (size_t j = 0u; j < sizeof r7s / sizeof r7s[0]; j++) {
                cogmaster *m = make(p);
                regs(m, configs[k].r0, configs[k].r1, 0x0Eu, 0x80u, 0x00u);
                m->vdp.reg[7] = (uint8_t)r7s[j];
                run(m);
                uint32_t n = r7s[j] & 15u;
                uint16_t want =
                    configs[k].legacy != 0u ? oracle_palette(p, n) : rgb444(cram_value(16u + n));
                CHECK_EQ_HEX(cogmaster__vdp_backdrop(m), want);
                CHECK_EQ_HEX(m->completed.backdrop, want);
                CHECK(m->completed.backdrop <= 0xFFFu);
                cogmaster_destroy(m);
            }
        }
    }
}

/* A register write at a dot, as the CPU would make it: the first control byte and the register byte
   at the same beam position. The renderer catches up to that dot before the register changes. */
static void write_reg(cogmaster *m, uint32_t line, uint32_t dot, uint32_t r, uint32_t v)
{
    m->bus.line = line;
    m->bus.t = 2u * dot;
    cogmaster__vdp_write(m, COGMASTER__VDP_CONTROL, (uint8_t)v);
    cogmaster__vdp_write(m, COGMASTER__VDP_CONTROL, (uint8_t)(0x80u | r));
}
static const size_t picture_bytes = (size_t)FIELD_H * FIELD_W * sizeof(uint16_t);

/* The eleven pairs of the Graphics II masks, a frame each on each profile: every dot equals the
   oracle and the hand-computed literals (g2_frame), the Master System 1 picture differs from the
   Master System 2 one for exactly the pairs that bite, and the Master System 2 and the Game Gear in
   Master System video mode draw the picture of the all-ones pair for every pair. */
static void masks(void)
{
    cogmaster *reference[PROFILE_COUNT];
    for (size_t k = 0u; k < 11u; k++) {
        cogmaster *frame[PROFILE_COUNT];
        for (enum profile p = PROFILE_SMS1; p < PROFILE_COUNT; p++) {
            frame[p] = g2_frame(p, pairs[k][0], pairs[k][1]);
            if (k == 0u)
                reference[p] = frame[p];
        }
        CHECK_EQ_U64(
            memcmp(frame[PROFILE_SMS1]->field, frame[PROFILE_SMS2]->field, picture_bytes) != 0,
            bites[k]);
        for (enum profile p = PROFILE_SMS2; p < PROFILE_COUNT; p++)
            CHECK(memcmp(frame[p]->field, reference[p]->field, picture_bytes) == 0);
        if (k != 0u)
            for (enum profile p = PROFILE_SMS1; p < PROFILE_COUNT; p++)
                cogmaster_destroy(frame[p]);
    }
    for (enum profile p = PROFILE_SMS1; p < PROFILE_COUNT; p++)
        cogmaster_destroy(reference[p]);
}

/* Rows, scroll and locks. A picture that latched 224 lines before the game selected Graphics II
   shows the backdrop from line 192 on; the display bit clear shows the colour RAM backdrop; R8, R9
   and R0 bits 5 to 7 change nothing. */
static void rows(void)
{
    for (enum profile p = PROFILE_SMS1; p < PROFILE_COUNT; p++) {
        cogmaster *m = make(p);
        scene_g2(m, 0x0Eu, 0xFFu, 0x03u);
        regs(m, 0x02u, 0x40u, 0x0Eu, 0xFFu, 0x03u);
        /* The beam starts at line 192 and the first call ends at a wrap, which latches the height
           from the registers, so the 224 lines are set after that call. The rows the 224 line
           picture adds hold a marker that only the renderer can replace. */
        run(m);
        m->vdp.height = 224u;
        for (uint32_t y = FIELD_H; y < 224u; y++)
            for (uint32_t x = 0u; x < FIELD_W; x++)
                m->field[y][x] = 0xABCDu;
        run(m);
        CHECK_EQ_U64(mismatches(m, p, 1, 0xFFu, 0x03u, 0u, FIELD_H), 0u);
        uint32_t bad = 0u;
        for (uint32_t y = FIELD_H; y < 224u; y++)
            for (uint32_t x = 0u; x < FIELD_W; x++)
                bad += m->field[y][x] != oracle_palette(p, BACKDROP_NIBBLE);
        CHECK_EQ_U64(bad, 0u);
        cogmaster_destroy(m);

        m = make(p);
        scene_g1(m, 0x0Eu, 0x80u, 0x00u);
        regs(m, 0x00u, 0x00u, 0x0Eu, 0x80u, 0x00u);
        run(m);
        bad = 0u;
        for (uint32_t y = 0u; y < FIELD_H; y++)
            for (uint32_t x = 0u; x < FIELD_W; x++)
                bad += m->field[y][x] != rgb444(cram_value(16u + BACKDROP_NIBBLE));
        CHECK_EQ_U64(bad, 0u);
        cogmaster_destroy(m);

        /* Two frames, so that the line latch of R8 and the frame latch of R9 have both taken their
           values: the horizontal scroll, the vertical scroll and the three R0 locks and masks
           change no dot of either mode. */
        for (uint32_t g2 = 0u; g2 < 2u; g2++) {
            m = make(p);
            if (g2 != 0u)
                scene_g2(m, 0x0Eu, 0xFFu, 0x03u);
            else
                scene_g1(m, 0x0Eu, 0x80u, 0x00u);
            regs(m, 0xE0u | (g2 << 1), 0x40u, 0x0Eu, g2 != 0u ? 0xFFu : 0x80u, g2 != 0u ? 3u : 0u);
            m->vdp.reg[8] = 0x35u;
            m->vdp.reg[9] = 0x2Bu;
            run(m);
            run(m);
            CHECK_EQ_U64(mismatches(m, p, (int)g2, 0xFFu, 0x03u, 0u, FIELD_H), 0u);
            cogmaster_destroy(m);
        }
    }
}

static cogmaster *picture_of(enum profile p, int g2)
{
    cogmaster *m = make(p);
    if (g2 != 0) {
        scene_g2(m, 0x0Eu, 0xFFu, 0x03u);
        regs(m, 0x02u, 0x40u, 0x0Eu, 0xFFu, 0x03u);
    } else {
        scene_g1(m, 0x0Eu, 0x80u, 0x00u);
        regs(m, 0x00u, 0x40u, 0x0Eu, 0x80u, 0x00u);
    }
    return m;
}

/* Calls in any pieces give one picture: a call per frame, a call per line, a call every 37 dots and
   two instances rendered in turn all equal the oracle. A call to a dot already reached moves no
   cursor and repaints nothing. */
static void intervals(void)
{
    for (enum profile p = PROFILE_SMS1; p < PROFILE_COUNT; p++) {
        for (int g2 = 0; g2 < 2; g2++) {
            cogmaster *whole = picture_of(p, g2), *lines = picture_of(p, g2);
            cogmaster *split = picture_of(p, g2), *twin = picture_of(p, g2);
            cogmaster__vdp_render_to(whole, FIELD_H);
            for (uint32_t y = 0u; y < FIELD_H; y++)
                cogmaster__vdp_render_until(lines, y, FIELD_W);
            for (uint32_t at = 37u; at < FIELD_H * FIELD_W; at += 37u) {
                cogmaster__vdp_render_until(split, at / FIELD_W, at % FIELD_W);
                /* The twin, another instance with the same inputs, is rendered in turn at other
                   dots: nothing is shared between the two. */
                if (at % 5u == 0u)
                    cogmaster__vdp_render_until(twin, at / FIELD_W, at % FIELD_W);
            }
            cogmaster__vdp_render_to(split, FIELD_H);
            cogmaster__vdp_render_to(twin, FIELD_H);
            CHECK_EQ_U64(mismatches(whole, p, g2, 0xFFu, 0x03u, 0u, FIELD_H), 0u);
            CHECK(memcmp(whole->field, lines->field, picture_bytes) == 0);
            CHECK(memcmp(whole->field, split->field, picture_bytes) == 0);
            CHECK(memcmp(whole->field, twin->field, picture_bytes) == 0);
            CHECK_EQ_U64(split->render_line * FIELD_W + split->render_x, FIELD_H * FIELD_W);
            cogmaster_destroy(whole);
            cogmaster_destroy(lines);
            cogmaster_destroy(split);
            cogmaster_destroy(twin);

            /* Idempotency: the cursor stops at (5, 100); calls to that dot or an earlier one leave
               it there and leave the dots already painted, which a stamp shows. */
            cogmaster *m = picture_of(p, g2);
            cogmaster__vdp_render_until(m, 5u, 100u);
            m->field[0][0] = 0x123u;
            m->field[5][99] = 0x456u;
            cogmaster__vdp_render_until(m, 5u, 100u);
            cogmaster__vdp_render_until(m, 5u, 50u);
            cogmaster__vdp_render_until(m, 0u, 0u);
            CHECK_EQ_U64(m->render_line, 5u);
            CHECK_EQ_U64(m->render_x, 100u);
            CHECK_EQ_HEX(m->field[0][0], 0x123u);
            CHECK_EQ_HEX(m->field[5][99], 0x456u);
            cogmaster__vdp_render_until(m, 5u, 101u);
            CHECK_EQ_U64(m->render_x, 101u);
            CHECK_EQ_HEX(m->field[5][99], 0x456u);
            CHECK_EQ_HEX(m->field[5][100], expect(p, g2, 0xFFu, 0x03u, 100u, 5u));
            cogmaster_destroy(m);
        }
    }
}

/* A register write is exact to its dot: R0 from mode 4 (nibble 8) to Graphics II (nibble 2) at dot
   100 of line 5. The dot before it draws mode 4, the write dot and every later one Graphics II, and
   every line before the write is mode 4. The same scene is a picture in either mode, so the
   reference frame in mode 4 differs from the oracle. */
static void sw(void)
{
    for (enum profile p = PROFILE_SMS1; p < PROFILE_COUNT; p++) {
        cogmaster *ref = make(p), *m = make(p);
        scene_g2(ref, 0x0Eu, 0xFFu, 0x03u);
        scene_g2(m, 0x0Eu, 0xFFu, 0x03u);
        regs(ref, 0x04u, 0x40u, 0x0Eu, 0xFFu, 0x03u);
        regs(m, 0x04u, 0x40u, 0x0Eu, 0xFFu, 0x03u);
        cogmaster__vdp_render_to(ref, FIELD_H);
        write_reg(m, 5u, 100u, 0u, 0x02u);
        CHECK_EQ_U64(m->vdp.reg[0], 0x02u);
        cogmaster__vdp_render_to(m, FIELD_H);
        CHECK(memcmp(m->field, ref->field, 5u * FIELD_W * sizeof(uint16_t)) == 0);
        CHECK(memcmp(m->field[5], ref->field[5], 100u * sizeof(uint16_t)) == 0);
        CHECK_EQ_U64(mismatches(m, p, 1, 0xFFu, 0x03u, 6u, FIELD_H), 0u);
        for (uint32_t x = 100u; x < FIELD_W; x++)
            CHECK_EQ_HEX(m->field[5][x], oracle_g2(p, 0xFFu, 0x03u, x, 5u));
        /* The switch is not vacuous: mode 4 draws other dots from the same memory. */
        CHECK(ref->field[5][99] != oracle_g2(p, 0xFFu, 0x03u, 99u, 5u));
        CHECK(ref->field[5][100] != oracle_g2(p, 0xFFu, 0x03u, 100u, 5u));
        CHECK_EQ_U64(m->fault_present, 0u);
        cogmaster_destroy(ref);
        cogmaster_destroy(m);
    }
}

/* Bring-up: a game turns the display on with the power-on mode, Graphics I, and writes R0 to select
   mode 4 later. The transient dots draw Graphics I and record no fault; the dots from the R0 write
   on equal a picture that was mode 4 throughout. */
static void bringup(void)
{
    for (enum profile p = PROFILE_SMS1; p < PROFILE_COUNT; p++) {
        cogmaster *ref = make(p), *m = make(p);
        scene_g1(ref, 0x0Eu, 0x80u, 0x00u);
        scene_g1(m, 0x0Eu, 0x80u, 0x00u);
        regs(ref, 0x04u, 0x40u, 0x0Eu, 0x80u, 0x00u);
        regs(m, 0x00u, 0x40u, 0x0Eu, 0x80u, 0x00u);
        cogmaster__vdp_render_to(ref, FIELD_H);
        write_reg(m, 7u, 40u, 0u, 0x04u);
        cogmaster__vdp_render_to(m, FIELD_H);
        CHECK_EQ_U64(m->fault_present, 0u);
        CHECK_EQ_U64(mismatches(m, p, 0, 0u, 0u, 0u, 7u), 0u);
        for (uint32_t x = 0u; x < 40u; x++)
            CHECK_EQ_HEX(m->field[7][x], oracle_g1(p, x, 7u));
        CHECK(memcmp(&m->field[7][40], &ref->field[7][40], (FIELD_W - 40u) * sizeof(uint16_t)) ==
              0);
        CHECK(memcmp(m->field[8], ref->field[8], (FIELD_H - 8u) * FIELD_W * sizeof(uint16_t)) == 0);
        /* Not vacuous: the reference is mode 4 from the first dot. */
        CHECK(memcmp(m->field[0], ref->field[0], 7u * FIELD_W * sizeof(uint16_t)) != 0);
        cogmaster_destroy(ref);
        cogmaster_destroy(m);
    }
}

/* A hostile program: every frame writes registers that select Graphics I or II (or, one frame in
   seven, text) with video memory full of garbage. Each frame ends within the 69-tick overshoot, and
   within a frame the cursor moves forward to exactly the dot asked for and never back. */
static void hostile(void)
{
    uint32_t seed = 0x2545F491u;
    for (enum profile p = PROFILE_SMS1; p < PROFILE_COUNT; p++) {
        cogmaster *m = make(p);
        for (uint32_t i = 0u; i < 60u; i++) {
            for (uint32_t j = 0u; j < sizeof m->vdp.vram; j++) {
                seed = seed * 1664525u + 1013904223u;
                m->vdp.vram[j] = (uint8_t)(seed >> 24);
            }
            uint32_t value[8];
            for (uint32_t r = 0u; r < 8u; r++) {
                seed = seed * 1664525u + 1013904223u;
                value[r] = seed >> 24;
            }
            value[0] &= 0xFBu;
            value[1] = 0xC0u | (value[1] & 3u) | ((i % 7u) == 6u ? 0x10u : 0u);
            for (uint32_t r = 0u; r < 8u; r++) {
                cogmaster__bus_out(m, 0xBFu, (uint8_t)value[r]);
                cogmaster__bus_out(m, 0xBFu, (uint8_t)(0x80u | r));
            }
            cogmaster_run_result res = {0};
            res.size = sizeof res;
            CHECK_EQ_U64(cogmaster_run_frame(m, &res), COGMASTER_STATUS_OK);
            CHECK(res.overshoot_ticks <= 69u);
            uint32_t cursor = m->render_line * FIELD_W + m->render_x;
            cogmaster__vdp_render_until(m, 0u, 0u);
            CHECK_EQ_U64(m->render_line * FIELD_W + m->render_x, cursor);
            m->vdp.display = 1u;
            for (uint32_t at = 0u; at < 40u * 1237u; at += 1237u) {
                cogmaster__vdp_render_until(m, at / FIELD_W, at % FIELD_W);
                CHECK_EQ_U64(m->render_line * FIELD_W + m->render_x, at);
            }
            cogmaster__vdp_render_to(m, m->vdp.height);
            CHECK_EQ_U64(m->render_line * FIELD_W + m->render_x, (uint32_t)m->vdp.height * FIELD_W);
            m->render_line = 0u;
            m->render_x = 0u;
        }
        cogmaster_destroy(m);
    }
}

/* ---- legacy sprites, the renderer driven in process and compared with oracle_sprites ---- */

/* R5 $7F puts the attribute table at $3F80 (32 entries of four bytes to the end of video memory);
   R6 = 3 puts the sprite generator at $1800, clear of the Graphics I and II scenes' tables (the
   Graphics II pattern and colour tables end at $37FF). The frame flag is bit 7 of the status after
   a frame. */
#define SAT_BASE 0x3F80u
#define GENERATOR_R6 3u
#define STATUS_FRAME 0x80u
#define STATUS_FIFTH 0x40u
#define STATUS_COINCIDENCE 0x20u

enum background { BG_BLANK, BG_G1, BG_G2 };

/* The status a program reads at a tick of a line; the read clears the flags. */
static uint8_t status_at(cogmaster *m, uint32_t line, uint32_t tick)
{
    m->bus.line = line;
    m->bus.t = tick;
    m->bus.at = m->ticks;
    return cogmaster__bus_in(m, 0xBFu);
}

/* The generated sprite patterns of oracle_sprites, by name and row. */
static void sprite_patterns(cogmaster *m, uint32_t r6)
{
    for (uint32_t n = 0u; n < 256u; n++)
        for (uint32_t r = 0u; r < 8u; r++)
            put(m, ((r6 & 7u) << 11) + 8u * n + r, pattern_byte(n, r));
}

/* The scene's attribute table: Y $D0 follows the last entry, which ends the list, and the entries
   are written last to first, or first to last when ascending: the list is the table order, not
   the order a program wrote it in. */
static void sprite_table(cogmaster *m, const struct scene *s, int ascending)
{
    if (s->count < 32u)
        put(m, SAT_BASE + 4u * s->count, 0xD0u);
    for (uint32_t k = 0u; k < s->count; k++) {
        uint32_t i = ascending ? k : s->count - 1u - k;
        put(m, SAT_BASE + 4u * i, s->e[i].y);
        put(m, SAT_BASE + 4u * i + 1u, s->e[i].x);
        put(m, SAT_BASE + 4u * i + 2u, s->e[i].name);
        put(m, SAT_BASE + 4u * i + 3u, s->e[i].attr);
    }
}

/* A frame of the scene on a blank background, on the Graphics I scene or on the Graphics II one. r0
   is R0 apart from the Graphics II bit; its bit 3 must change nothing. */
static cogmaster *sprite_frame(enum profile p, const struct scene *s, enum background bg,
                               uint32_t r0, int ascending)
{
    cogmaster *m = make(p);
    if (bg == BG_G1)
        scene_g1(m, 0x0Eu, 0x80u, 0x00u);
    if (bg == BG_G2)
        scene_g2(m, 0x0Eu, 0xFFu, 0x03u);
    sprite_patterns(m, GENERATOR_R6);
    sprite_table(m, s, ascending);
    m->vdp.reg[6] = GENERATOR_R6;
    regs(m, (bg == BG_G2 ? 0x02u : 0x00u) | r0, 0x40u | s->r1, 0x0Eu, bg == BG_G2 ? 0xFFu : 0x80u,
         bg == BG_G2 ? 0x03u : 0x00u);
    return m;
}

/* The dot the oracles give: the sprite colour where there is one, the background otherwise. */
static uint16_t sprite_expect(enum profile p, const struct scene *s, enum background bg, uint32_t x,
                              uint32_t y)
{
    uint32_t colour = oracle_sprites(s, y, x).colour;
    if (colour != 0u)
        return oracle_palette(p, colour);
    if (bg == BG_G1)
        return oracle_g1(p, x, y);
    if (bg == BG_G2)
        return oracle_g2(p, 0xFFu, 0x03u, x, y);
    return oracle_palette(p, BACKDROP_NIBBLE);
}

/* The dots of lines 0 to 191 that differ from the oracles; the first is printed. */
static uint32_t sprite_mismatches(const cogmaster *m, enum profile p, const struct scene *s,
                                  enum background bg)
{
    uint32_t bad = 0u;
    for (uint32_t y = 0u; y < FIELD_H; y++) {
        for (uint32_t x = 0u; x < FIELD_W; x++) {
            uint16_t want = sprite_expect(p, s, bg, x, y);
            if (m->field[y][x] != want && bad++ == 0u)
                fprintf(stderr, "profile %d (%u,%u) is %03x, expected %03x\n", (int)p, x, y,
                        m->field[y][x], want);
        }
    }
    return bad;
}

/* The SAT index of the fifth Y match on the line, or -1. Every match counts, drawn or not. */
static int fifth_match(const struct scene *s, uint32_t line)
{
    int span = ((s->r1 & 2u) != 0u ? 16 : 8) * ((s->r1 & 1u) != 0u ? 2 : 1), matches = 0;
    for (uint32_t i = 0u; i < s->count && i < 32u && s->e[i].y != 0xD0u; i++) {
        int top = s->e[i].y >= 0xE0u ? (int)s->e[i].y - 255 : (int)s->e[i].y + 1;
        if ((int)line >= top && (int)line < top + span && ++matches == 5)
            return (int)i;
    }
    return -1;
}

/* The status the oracles give at the end of a frame: the frame flag, the coincidence of any line,
   and the fifth sprite flag with the index of the first fifth match in raster order, or 31. */
static uint32_t scene_status(const struct scene *s)
{
    uint32_t coincidence = 0u;
    int fifth = -1;
    for (uint32_t line = 0u; line < FIELD_H; line++) {
        if (fifth < 0)
            fifth = fifth_match(s, line);
        coincidence |= line_coincidence(s, line);
    }
    return STATUS_FRAME | (coincidence != 0u ? STATUS_COINCIDENCE : 0u) |
           (fifth >= 0 ? STATUS_FIFTH | (uint32_t)fifth : 0x1Fu);
}

/* One frame of the scene on the three profiles: every dot of lines 0 to 191 equals the oracles,
   nothing is a fault, and the status read at the end of the frame is the hand-computed want, which
   the oracles also give. */
static void sprite_scene(const struct scene *s, enum background bg, uint32_t r0, uint32_t want)
{
    CHECK_EQ_HEX(scene_status(s), want);
    for (enum profile p = PROFILE_SMS1; p < PROFILE_COUNT; p++) {
        cogmaster *m = sprite_frame(p, s, bg, r0, 0);
        run(m);
        CHECK_EQ_U64(sprite_mismatches(m, p, s, bg), 0u);
        CHECK_EQ_U64(m->fault_present, 0u);
        CHECK_EQ_HEX(status_at(m, 192u, 608u), want);
        cogmaster_destroy(m);
    }
}

/* A dot against a palette entry; colour 0 is the backdrop of a blank background. */
static void dot_is(const cogmaster *m, enum profile p, uint32_t x, uint32_t y, uint32_t colour)
{
    CHECK_EQ_HEX(m->field[y][x], oracle_palette(p, colour != 0u ? colour : BACKDROP_NIBBLE));
}

/* Colour 5 of the scenes: fixed entry 5 is F00; colour RAM entry 21 is (13 * 21 + 5) & 63 = 22 =
   010110, blue 1, green 1, red 2: 55A. */
static const uint16_t colour5[PROFILE_COUNT] = {0xF00, 0xF00, 0x55A};

/* One 8 by 8 sprite over Graphics I, on three profiles, as a solid sprite and as a patterned one
   (name 12, colour 13: its rows differ and its colour has bit 3 set): every dot of every line
   equals the oracles (the sprite on its eight lines and eight dots, the background elsewhere),
   nothing is a fault, and the status holds the frame flag alone. The solid sprite's corners are
   the hand-computed colour 5. */
static void sprites_basic(void)
{
    static const struct scene patterned = {0u, 1u, {{39, 100, 12, 13}}};
    for (enum profile p = PROFILE_SMS1; p < PROFILE_COUNT; p++) {
        for (uint32_t k = 0u; k < 2u; k++) {
            const struct scene *s = k == 0u ? &lone : &patterned;
            cogmaster *m = sprite_frame(p, s, BG_G1, 0x00u, 0);
            run(m);
            CHECK_EQ_U64(sprite_mismatches(m, p, s, BG_G1), 0u);
            CHECK_EQ_U64(m->fault_present, 0u);
            /* Not vacuous: the picture without the sprite has other dots on its lines. */
            uint32_t differ = 0u;
            for (uint32_t y = 40u; y < 48u; y++)
                for (uint32_t x = 100u; x < 108u; x++)
                    differ += m->field[y][x] != oracle_g1(p, x, y);
            CHECK(differ >= (k == 0u ? 32u : 8u));
            CHECK_EQ_HEX(status_at(m, 192u, 608u), 0x9Fu);
            CHECK_EQ_HEX(scene_status(s), 0x9Fu);
            if (k == 0u) {
                CHECK_EQ_HEX(m->field[40][100], colour5[p]);
                CHECK_EQ_HEX(m->field[47][107], colour5[p]);
            }
            cogmaster_destroy(m);
        }
    }
}

/* A 16 by 16 sprite at Y 39, X 100 with name 13: the name's two low bits are cleared, so the four
   quadrants are the patterns 12 (top left), 13 (bottom left), 14 (top right) and 15 (bottom right).
   Row 0 of those patterns is 7D, B2, E7 and 1C. */
static const struct scene big = {2u, 1u, {{39, 100, 13, 6}}};
/* Two solid sprites at one X, the lower index first in the table and the higher colour second. */
static const struct scene same_x = {0u, 2u, {{59, 100, 1, 5}, {59, 100, 1, 6}}};

/* Sizes and order. 8 by 8 sprites are the patterns of their name; 16 by 16 ones are four, whose
   quadrants are checked with the dots that tell the order apart (a top left, top right, bottom
   left, bottom right order puts E7 where B2 belongs). Two opaque sprites on one dot show the lower
   index, whether the program wrote its entry first or last, at a different X or the same one. */
static void sprites_sizes(void)
{
    sprite_scene(&big, BG_BLANK, 0x00u, 0x9Fu);
    sprite_scene(&big, BG_G2, 0x00u, 0x9Fu);
    sprite_scene(&opaque, BG_BLANK, 0x00u, 0xBFu);
    sprite_scene(&same_x, BG_BLANK, 0x00u, 0xBFu);
    for (enum profile p = PROFILE_SMS1; p < PROFILE_COUNT; p++) {
        cogmaster *m = sprite_frame(p, &big, BG_BLANK, 0x00u, 0);
        run(m);
        dot_is(m, p, 100u, 40u, 0u); /* 7D is 01111101: bit 7 clear, bit 6 set */
        dot_is(m, p, 101u, 40u, 6u);
        dot_is(m, p, 100u, 48u, 6u); /* B2 is 10110010: bit 7 set, bit 6 clear */
        dot_is(m, p, 101u, 48u, 0u);
        dot_is(m, p, 109u, 40u, 6u); /* E7 is 11100111: bit 6 set; B2 has it clear */
        dot_is(m, p, 111u, 40u, 0u);
        dot_is(m, p, 111u, 48u, 6u); /* 1C is 00011100: bit 4 set, bit 7 clear */
        dot_is(m, p, 108u, 48u, 0u);
        dot_is(m, p, 115u, 55u, 6u); /* the last dot of the last line: 15 row 7 is 93, bit 0 set */
        dot_is(m, p, 116u, 40u, 0u);
        dot_is(m, p, 100u, 56u, 0u);
        cogmaster_destroy(m);

        cogmaster *down = sprite_frame(p, &same_x, BG_BLANK, 0x00u, 0);
        cogmaster *up = sprite_frame(p, &same_x, BG_BLANK, 0x00u, 1);
        run(down);
        run(up);
        CHECK(memcmp(down->field, up->field, picture_bytes) == 0);
        for (uint32_t x = 100u; x < 108u; x++)
            dot_is(down, p, x, 60u, 5u);
        dot_is(down, p, 108u, 60u, 0u);
        cogmaster_destroy(down);
        cogmaster_destroy(up);
    }
}

