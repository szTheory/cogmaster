static void oracle(void)
{
    for (size_t i = 0u; i < sizeof palette_cases / sizeof palette_cases[0]; i++) {
        const struct palette_case *c = &palette_cases[i];
        uint16_t got = oracle_palette(c->profile, c->nibble);
        if (got != c->want)
            fprintf(stderr, "palette %zu: profile %d entry %u is %03x, expected %03x\n", i,
                    (int)c->profile, c->nibble, got, c->want);
        CHECK_EQ_HEX(got, c->want);
    }
    for (size_t i = 0u; i < sizeof g1_cases / sizeof g1_cases[0]; i++) {
        const struct dot_case *c = &g1_cases[i];
        uint16_t got = oracle_g1(c->profile, c->x, c->y);
        if (got != c->want)
            fprintf(stderr, "g1 %zu: profile %d (%u,%u) is %03x, expected %03x\n", i,
                    (int)c->profile, c->x, c->y, got, c->want);
        CHECK_EQ_HEX(got, c->want);
    }
    for (size_t i = 0u; i < sizeof g2_cases / sizeof g2_cases[0]; i++) {
        const struct dot_case *c = &g2_cases[i];
        uint16_t got = oracle_g2(c->profile, c->r3, c->r4, c->x, c->y);
        if (got != c->want)
            fprintf(stderr, "g2 %zu: profile %d R3 %02x R4 %02x (%u,%u) is %03x, expected %03x\n",
                    i, (int)c->profile, c->r3, c->r4, c->x, c->y, got, c->want);
        CHECK_EQ_HEX(got, c->want);
    }
    for (size_t i = 0u; i < sizeof sprite_cases / sizeof sprite_cases[0]; i++) {
        const struct sprite_case *c = &sprite_cases[i];
        struct sprite_dot got = oracle_sprites(c->scene, c->line, c->x);
        if (got.colour != c->colour || got.coincidence != c->coincidence)
            fprintf(stderr,
                    "sprite %zu: line %u dot %u is colour %u coincidence %u, expected %u %u\n", i,
                    c->line, c->x, got.colour, got.coincidence, c->colour, c->coincidence);
        CHECK_EQ_U64(got.colour, c->colour);
        CHECK_EQ_U64(got.coincidence, c->coincidence);
    }
    /* Two 8 by 8 sprites at X $FF whose set bits lie only in pattern columns 1 to 7 overlap only at
       dots 256 to 262, past the 0 to 255 bound: no coincidence on the line, and dot 255 (column 0,
       clear) draws nothing. The same pair at X $F8 overlaps on dots 249 to 255: a coincidence. */
    CHECK_EQ_U64(line_coincidence(&edge, 60u), 0u);
    CHECK_EQ_U64(oracle_sprites(&edge, 60u, 255u).colour, 0u);
    CHECK_EQ_U64(line_coincidence(&edge_in, 60u), 1u);
    CHECK_EQ_U64(oracle_sprites(&edge_in, 60u, 255u).coincidence, 1u);
    CHECK_EQ_U64(oracle_sprites(&edge_in, 60u, 248u).coincidence, 0u);
    /* The eleven (R3, R4) pairs. Only the Master System 1 masks: the other two profiles draw the
       same picture for every pair, because the scene is generated per index. The Master System 1
       differs from the Master System 2 for nine pairs; $FF and $03, and $7F and $07, have all the
       mask bits set and change nothing (worked out from the mask arithmetic above). */
    static const uint8_t pairs[11][2] = {{0xFF, 0x03}, {0x7F, 0x07}, {0xFF, 0x00}, {0xFF, 0x01},
                                         {0xFF, 0x02}, {0x80, 0x03}, {0x9F, 0x03}, {0xBF, 0x03},
                                         {0xDF, 0x03}, {0xFE, 0x03}, {0xE0, 0x03}};
    static const uint32_t bites[11] = {0u, 0u, 1u, 1u, 1u, 1u, 1u, 1u, 1u, 1u, 1u};
    for (size_t k = 0u; k < 11u; k++) {
        uint32_t differ = 0u, sms2_moves = 0u, gg_moves = 0u;
        for (uint32_t y = 0u; y < FIELD_H; y++) {
            for (uint32_t x = 0u; x < FIELD_W; x++) {
                uint16_t sms1 = oracle_g2(PROFILE_SMS1, pairs[k][0], pairs[k][1], x, y);
                uint16_t sms2 = oracle_g2(PROFILE_SMS2, pairs[k][0], pairs[k][1], x, y);
                uint16_t gg = oracle_g2(PROFILE_GG, pairs[k][0], pairs[k][1], x, y);
                differ |= sms1 != sms2;
                sms2_moves |= sms2 != oracle_g2(PROFILE_SMS2, 0xFFu, 0x03u, x, y);
                gg_moves |= gg != oracle_g2(PROFILE_GG, 0xFFu, 0x03u, x, y);
            }
        }
        CHECK_EQ_U64(differ, bites[k]);
        CHECK_EQ_U64(sms2_moves, 0u);
        CHECK_EQ_U64(gg_moves, 0u);
    }
}

int main(int argc, char **argv)
{
    if (argc != 2)
        return 2;
    if (strcmp(argv[1], "oracle") == 0)
        oracle();
    else
        return 2;
    CHECK_DONE();
}
